/** Where the per-user boot-autostart entry lives for one platform. */
function autostartDir(platform, home) {
	switch (platform) {
		case "win32": {
			const appdata = process.env.APPDATA && process.env.APPDATA.trim() !== "" ? process.env.APPDATA : `${home}\\AppData\\Roaming`;
			return `${appdata}\\Microsoft\\Windows\\Start Menu\\Programs\\Startup`;
		}
		case "darwin": return `${home}/Library/LaunchAgents`;
		case "linux": return `${home}/.config/autostart`;
	}
}
