/**
* Fill defaults from a partial config (schema defaults may be absent in
* hand-built test contexts). An empty profile means "no --profile flag".
* @param config - partial launcher config.
* @returns the resolved spec.
*/
function resolveLauncherSpec(config) {
	return {
		dshCommand: config.dshCommand ?? "dsh",
		url: config.url ?? "http://127.0.0.1:3080",
		...config.profile === void 0 || config.profile === "" ? {} : { profile: config.profile },
		...config.iconPath === void 0 || config.iconPath === "" ? {} : { iconPath: config.iconPath }
	};
}
