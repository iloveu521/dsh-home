/**
* Mount the route and announcement, gated on the composition entry config
* (and the live settings value once the web settings surface is served).
* @param ctx - host plugin context carrying webServer/systemPrompt.
* @param config - resolved plugin config (schema defaults applied by the loader).
*/
const apply = mountOnce("@linxin666/dsh-desktop-launcher", applyImpl);
function applyImpl(ctx, config) {
	let current = () => config ?? {};
	let disposeRoutes;
	let disposeShutdownRoute;
	let disposeSection;
	/** Ask the launcher for a bounded exit; fall back to a direct exit. */
	const requestExit = (code) => {
		const exit = ctx.get("appExit");
		if (exit !== void 0) {
			exit(code);
			return;
		}
		process.exit(code);
	};
	/** The live launcher spec resolver shared by routes and autostart sync. */
	const resolveSpec = () => resolveLauncherSpec(current());
	/**
	 * Reconcile the OS-level autostart entry with the configured desire.
	 * Never throws: a failing registration must not take the plugin down —
	 * the settings card reports live state through the status endpoint.
	 */
	/**
	 * Reconcile the OS-level autostart entry with the configured desire.
	 * Never throws: a failing registration must not take the plugin down —
	 * the settings card reports live state through the status endpoint.
	 * @param desired - the wanted registration state; the master switch wins,
	 * so a disabled plugin always reports false.
	 */
	const syncAutostart = async (desired) => {
		try {
			const status = await getAutostartStatus({ resolveSpec });
			if (desired && !status.registered) await enableAutostart({ resolveSpec });
			else if (!desired && status.registered) await disableAutostart({ resolveSpec });
		} catch (error) {
			console.warn("[dsh-desktop-launcher] autostart sync failed:", error instanceof Error ? error.message : String(error));
		}
	};
	const sync = () => {
		if (disposeSection !== void 0) {
			disposeSection();
			disposeSection = void 0;
		}
		if (disposeRoutes !== void 0) {
			disposeRoutes();
			disposeRoutes = void 0;
		}
		if (disposeShutdownRoute !== void 0) {
			disposeShutdownRoute();
			disposeShutdownRoute = void 0;
		}
		const value = current();
		if ((value.enabled ?? true) === false) {
			// Master switch wins: a disabled plugin never leaves a login entry
			// behind pointing at scripts it no longer maintains.
			void syncAutostart(false);
			return;
		}
		disposeRoutes = ctx.effect(() => {
			const disposers = makeRoutes({ resolveSpec }).routes.map((route) => ctx.webServer.register(route));
			return () => {
				for (const dispose of disposers) dispose();
			};
		}, "dsh-desktop-launcher: routes");
		disposeShutdownRoute = ctx.effect(() => ctx.webServer.register(makeShutdownRoute({
			fence: isLoopbackRequest,
			requestExit
		})), "dsh-desktop-launcher: shutdown route");
		if ((value.announceToAgent ?? DEFAULT_ANNOUNCE) !== false) disposeSection = ctx.systemPrompt.section({
			name: "plugin:dsh-desktop-launcher",
			order: SECTION_ORDER,
			text: DESKTOP_LAUNCHER_GUIDANCE
		});
		void syncAutostart((value.autostart ?? false) === true);
	};
	installSettingsSection(ctx, DESKTOP_LAUNCHER_SETTINGS_NAMESPACE, Config, config ?? {}, {
		setSource: (source) => {
			current = source;
			sync();
		},
		onChange: sync
	});
	sync();
}
